import type { Quiz, Unit } from "../../types";
import { scopedQuizId } from "../../lib/quizId";

const SUBJECT_ID = "seomgang-tech";

function q(
  unitId: string,
  num: number,
  data: Omit<Quiz, "id">
): Quiz {
  return {
    id: scopedQuizId(
      SUBJECT_ID,
      `${unitId}-q${String(num).padStart(2, "0")}`
    ),
    ...data,
  };
}

function opts(texts: string[]) {
  return texts.map((text, i) => ({
    id: ["a", "b", "c", "d"][i]!,
    text,
  }));
}

